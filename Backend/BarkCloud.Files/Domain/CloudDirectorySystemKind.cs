namespace BarkCloud.Files.Domain;

/// <summary>
/// Тип системной (автоматически создаваемой) папки. None — обычная пользовательская папка.
/// Системные папки находятся по этому флагу, а не по имени, поэтому устойчивы к переименованию
/// пользователем и не дублируются. Используются для авто-распределения загрузок по типу медиа.
/// </summary>
public enum CloudDirectorySystemKind
{
    None = 0,
    Photos = 1,
    Videos = 2,
    OtherDocuments = 3
}
